  function build() {
    const blank = [0, 0, 0, 0, 0, 0, 0, 0];
    const lower = new Array(128).fill(null), upper = new Array(128).fill(null);
    const pun = ' !"#$%&\'()*+,-./0123456789:;<=>?';
    for (let i = 0; i < 32; i++) { lower[0x20 + i] = upper[0x20 + i] = toBits(G[pun[i]]); }
    lower[0x00] = upper[0x00] = toBits(G['@']);
    for (let i = 0; i < 26; i++) {
      lower[0x01 + i] = toBits(G[String.fromCharCode(97 + i)]);
      lower[0x41 + i] = toBits(G[String.fromCharCode(65 + i)]);
      upper[0x01 + i] = toBits(G[String.fromCharCode(65 + i)]);
    }
    for (const [c, ch] of [[0x1B, '['], [0x1C, '£'], [0x1D, ']'], [0x1E, '↑'], [0x1F, '←']]) lower[c] = upper[c] = toBits(G[ch]);
    for (const k in GFX) { const bits = fill(GFX[k]); lower[k] = bits; if (+k < 0x41 || +k > 0x5A) upper[k] = bits; }
    // nel set grafico $41-$5A sono simboli: approssimati con tratteggi diversi
    for (let i = 0x41; i <= 0x5A; i++) if (!upper[i]) upper[i] = fill((x, y) => ((x * 3 + y * 5 + i) % 7) < 2);
    for (let i = 0; i < 128; i++) { if (!lower[i]) lower[i] = blank; if (!upper[i]) upper[i] = blank; }
    return [upper, lower];
  }

